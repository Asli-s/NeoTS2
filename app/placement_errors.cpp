// The kinds of floor (object data 0x2A bits) in the order the list names them, each with its line
// in a list and its line as a message of its own (UI text 0xAD).
struct Kind {
    std::uint16_t bit;
    std::uint32_t item, alone;
};
constexpr Kind kFloorKindLines[] = {{0x0001, 2, 9},   {0x0002, 1, 8},   {0x4000, 4, 0x0B},
                                    {0x0004, 5, 0x0C}, {0x0800, 6, 0x0D}, {0x2000, 7, 0x0E}};
// The surfaces (object data 4 bits) the same way (UI text 0xAE): coffee table, dining table or desk,
// counter, seat, end table, in a countertop, under a counter and driveway.
constexpr Kind kSurfaceLines[] = {{0x0002, 1, 8},     {0x0004, 2, 9},     {0x0008, 3, 0x0A}, {0x0040, 4, 0x0B},
                                  {0x0080, 5, 0x0C},  {0x0100, 6, 0x0D},  {0x0200, 7, 0x0E}, {0x0800, 0x0F, 0x10}};

