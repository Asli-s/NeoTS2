std::uint32_t placementErrorLine(int code) {
    const auto* found = std::find_if(std::begin(kLines), std::end(kLines), [&](const auto& l) { return l.first == code; });
    return found != std::end(kLines) ? found->second : 1;
}

std::string placementErrorText(const UiLine& text, int code, std::uint16_t heights, std::uint16_t placement) {
    const std::uint32_t line = placementErrorLine(code);
    if (line == 0) {
        return {};
    }
    if (line != kListHeader) {
        return text(kErrors, line);
    }
    // The kinds of floor count only for an object that may stand on the floor (data 4 bit 0x01).
    constexpr std::uint16_t kOnTheFloor = 0x0001;
    std::vector<std::pair<std::uint32_t, const Kind*>> spots;
    if ((heights & kOnTheFloor) != 0) {
        for (const Kind& k : kFloorKindLines) {
            if ((placement & k.bit) != 0) {
                spots.emplace_back(kFloorKinds, &k);
            }
        }
    }
    for (const Kind& k : kSurfaceLines) {
        if ((heights & k.bit) != 0) {
            spots.emplace_back(kSurfaces, &k);
        }
    }
    // One spot is its own message, more are listed under a header, each after the list's separator.
    if (spots.size() == 1) {
        return text(spots[0].first, spots[0].second->alone);
    }
    if (spots.empty()) {
        return {};
    }
    std::string out = text(kErrors, kListHeader);
    for (const auto& [table, kind] : spots) {
        out += text(kErrors, kListSeparator) + text(table, kind->item);
    }
    return out;
}

